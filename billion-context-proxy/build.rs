//! Collect the build identity at compile time.
//!
//! The identity is deliberately made of things that only change when the source
//! or the build configuration changes — the package version, the checked-out
//! commit and the cargo profile. A per-build timestamp is *not* used: two builds
//! of the same commit must report the same identity.
//!
//! Everything here is fail-open. If git is missing, the checkout has no `.git`,
//! or the command fails, the identity degrades to `unknown` and the build still
//! succeeds. A host that cannot state its commit is far better than a host that
//! cannot be built.
//!
//! # Layout
//!
//! This package is a *subdirectory* of a larger repository (`rust/billion-context-proxy` in
//! the ezxss workspace), not a repository of its own. Two consequences shape
//! everything below:
//!
//! * The commit is the enclosing repository's HEAD. That is the correct answer:
//!   the code being compiled is exactly what that commit contains at this path.
//! * The dirty flag must be scoped to this directory. The enclosing repository
//!   is dirty almost all the time for reasons unrelated to this package, so an
//!   unscoped `git status` would report `dirty` on every release build and make
//!   `release.ps1`'s cleanliness gate impossible to satisfy.
//!
//! Both are handled by running git from the package root (which cargo makes the
//! working directory) and passing `.` as an explicit pathspec.
//!
//! # Watch set
//!
//! Cargo re-runs this script only when something in the *watch set* changes, and
//! it only learns the watch set from the `rerun-if-changed` lines printed here.
//! Printing even one of them disables cargo's default "any file in the package"
//! behaviour, so the set has to be complete on its own: a watch set of just
//! `.git/HEAD` and `.git/index` misses every working-tree change that leaves the
//! index alone — a new untracked file, or an edit to a tracked file outside the
//! Rust source graph. Both were observed to leave a stale `dirty=false` behind,
//! which is the exact failure mode this identity exists to prevent.
//!
//! The set is built from two parts:
//!
//! * The package tree, which covers the whole source graph because a watched
//!   directory is watched recursively. Two shapes are used, chosen by where cargo
//!   put the build directory:
//!   - `target/` is outside the package (the release path, `C:\bc-target`):
//!     watch `.`. Nothing cargo writes lands inside the package, so a rebuild
//!     cannot retrigger itself, and a brand-new file anywhere in the package is
//!     noticed.
//!   - `target/` is inside the package (a plain `cargo build`): watching `.` would
//!     be self-triggering, because every build writes new files under `target/`.
//!     The top-level entries are enumerated instead, skipping the noisy ones. The
//!     cost is that a brand-new file created directly in the package root is not
//!     noticed until the next real change; anything below the root is covered.
//!     `git status` still reports it, so `release.ps1` refuses to publish a dirty
//!     tree regardless.
//! * The git metadata that moves without touching the working tree: HEAD on
//!   commit/checkout, index on staging, refs on branch and tag updates. These live
//!   in the enclosing repository, so their paths are resolved with
//!   `git rev-parse --absolute-git-dir` rather than being assumed to be `.git`.

use std::env;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Top level entries that never carry source: cargo output, packaged binaries,
/// VCS metadata and logs.
const NOISE_DIRS: &[&str] = &["target", "dist", ".git", "logs", "node_modules"];

/// Run a git command in the package root with index refreshing disabled, so
/// reading the state cannot itself make the state change (and trigger an endless
/// `rerun-if-changed` rebuild loop).
fn git(args: &[&str]) -> Option<String> {
    let out = Command::new("git")
        .args(args)
        .env("GIT_OPTIONAL_LOCKS", "0")
        .env("GIT_TERMINAL_PROMPT", "0")
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let text = String::from_utf8(out.stdout).ok()?;
    let trimmed = text.trim();
    if trimmed.is_empty() {
        None
    } else {
        Some(trimmed.to_string())
    }
}

fn is_noise(name: &str) -> bool {
    if NOISE_DIRS.contains(&name) {
        return true;
    }
    let lower = name.to_ascii_lowercase();
    // Backups, logs and packaged binaries are regenerated by the release
    // scripts; watching them would rebuild after every packaging run.
    lower.ends_with(".bak")
        || lower.ends_with(".log")
        || lower.ends_with(".exe")
        || lower.ends_with(".pdb")
}

/// The metadata directory of the enclosing repository, resolved rather than
/// assumed, because this package is nested inside another repository.
fn absolute_git_dir() -> Option<PathBuf> {
    git(&["rev-parse", "--absolute-git-dir"]).map(PathBuf::from)
}

/// True when cargo's output directory for this build sits inside the package,
/// which is when watching `.` would retrigger itself.
fn target_inside_package(package: &Path) -> bool {
    match env::var("OUT_DIR") {
        Ok(out) => PathBuf::from(out).starts_with(package),
        // Unknown layout: assume the self-triggering one, since falling back to
        // `.` there is the failure that costs the most (an endless rebuild).
        Err(_) => true,
    }
}

fn emit_watch_set(package: &Path) {
    if !target_inside_package(package) {
        println!("cargo::rerun-if-changed=.");
    } else if let Ok(entries) = std::fs::read_dir(package) {
        let mut names: Vec<String> = entries
            .filter_map(|entry| entry.ok())
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .filter(|name| !is_noise(name))
            .collect();
        names.sort();
        for name in names {
            println!("cargo::rerun-if-changed={name}");
        }
    }

    // Git metadata: HEAD moves on commit/checkout, index on staging, refs on
    // branch and tag updates. These are what make a rebuild pick up a new SHA.
    // They live in the enclosing repository, so print absolute paths; the
    // relative `.git/...` form does not exist under a nested package.
    if let Some(dir) = absolute_git_dir() {
        for meta in ["HEAD", "index", "refs"] {
            println!("cargo::rerun-if-changed={}", dir.join(meta).display());
        }
    }
}

fn main() {
    if let Ok(dir) = env::var("CARGO_MANIFEST_DIR") {
        emit_watch_set(&PathBuf::from(dir));
    }
    // If the manifest directory cannot be read, keep cargo's default
    // package-wide watching rather than pinning a set that might be wrong.

    // An explicit identity, used by the release script so that the published
    // binary's identity is decided by the checks the script just ran instead of
    // by whatever cargo happened to cache.
    println!("cargo::rerun-if-env-changed=BILI_BUILD_COMMIT");
    println!("cargo::rerun-if-env-changed=BILI_BUILD_DIRTY");

    let commit = env::var("BILI_BUILD_COMMIT")
        .ok()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .or_else(|| git(&["rev-parse", "--short=12", "HEAD"]))
        .unwrap_or_else(|| "unknown".to_string());

    let dirty = match env::var("BILI_BUILD_DIRTY")
        .ok()
        .map(|value| value.trim().to_string())
        .as_deref()
    {
        Some("1") | Some("true") => true,
        Some("0") | Some("false") => false,
        // `.` scopes the check to this package. In a standalone checkout that is
        // the whole repository (same answer as before); nested inside a larger
        // one it is the only way to get an answer about *this* code.
        _ => git(&[
            "status",
            "--porcelain",
            "--untracked-files=normal",
            "--",
            ".",
        ])
        .map(|text| !text.is_empty())
        .unwrap_or(false),
    };

    let profile = env::var("PROFILE").unwrap_or_else(|_| "unknown".to_string());

    println!("cargo::rustc-env=BILI_BUILD_COMMIT={commit}");
    println!(
        "cargo::rustc-env=BILI_BUILD_DIRTY={}",
        if dirty { "1" } else { "0" }
    );
    println!("cargo::rustc-env=BILI_BUILD_PROFILE={profile}");
}
